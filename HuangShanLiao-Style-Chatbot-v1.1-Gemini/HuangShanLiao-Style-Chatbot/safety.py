CRISIS_KEYWORDS = [
    "自殺", "自殘", "割腕", "想死", "不想活",
    "傷害自己", "結束生命", "輕生"
]

def is_high_risk(text: str) -> bool:
    return any(k in text for k in CRISIS_KEYWORDS)

